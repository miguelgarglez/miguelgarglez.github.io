// Mirrors the Worker profile agent into the Vercel fallback.
// The fallback deploys from chat-backup-vercel/ and cannot import files outside
// that root, so it gets a generated copy. Edit the Worker sources, then run:
//   node scripts/sync-backup-agent.mjs          (write)
//   node scripts/sync-backup-agent.mjs --check  (fail on drift)
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join, posix, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

// Tests bundle this module, so callers can pass the repo root explicitly.
let repoRoot = process.cwd();
export const MIRROR_DIR = 'chat-backup-vercel/shared/profile-agent';
const HEADER =
  '// GENERATED by scripts/sync-backup-agent.mjs from the Worker sources. Do not edit.\n';

function listTs(dir) {
  return readdirSync(join(repoRoot, dir))
    .filter((name) => name.endsWith('.ts'))
    .sort()
    .map((name) => `${dir}/${name}`);
}

// source path (repo-relative) -> mirror path (relative to MIRROR_DIR)
export function sourceMap() {
  const map = new Map();
  for (const file of listTs('chat-worker/src/agent')) map.set(file, `agent/${posix.basename(file)}`);
  for (const file of listTs('chat-worker/src/knowledge')) map.set(file, `knowledge/${posix.basename(file)}`);
  map.set('chat-worker/src/ui-stream.ts', 'ui-stream.ts');
  map.set('shared/chat-parts.ts', 'deps/chat-parts.ts');
  map.set('cv-chat/src/data/experience.ts', 'deps/cv-chat-experience.ts');
  map.set('src/data/projects.ts', 'deps/site-projects.ts');
  return map;
}

function rewrite(source, from, map) {
  const fromDir = posix.dirname(from);
  const target = posix.dirname(map.get(from));
  return source.replace(/(from\s+|import\s+)(['"])(\.{1,2}\/[^'"]+)\2/g, (whole, kw, q, spec) => {
    let resolved = posix.normalize(posix.join(fromDir, spec));
    if (!resolved.endsWith('.ts')) resolved += '.ts';
    const dest = map.get(resolved);
    if (!dest) throw new Error(`${from} imports ${spec} (${resolved}), which is not mirrored`);
    let rel = posix.relative(target, dest).replace(/\.ts$/, '.js');
    if (!rel.startsWith('.')) rel = `./${rel}`;
    return `${kw}${q}${rel}${q}`;
  });
}

export function buildMirror() {
  const map = sourceMap();
  const out = new Map();
  for (const [from, to] of map) {
    out.set(to, HEADER + rewrite(readFileSync(join(repoRoot, from), 'utf8'), from, map));
  }
  return out;
}

function existingFiles(dir, base = '') {
  const abs = join(repoRoot, MIRROR_DIR, base);
  if (!existsSync(abs)) return [];
  return readdirSync(abs, { withFileTypes: true }).flatMap((entry) =>
    entry.isDirectory()
      ? existingFiles(dir, posix.join(base, entry.name))
      : [posix.join(base, entry.name)]
  );
}

export function findDrift(root = repoRoot) {
  repoRoot = root;
  const expected = buildMirror();
  const problems = [];
  for (const [file, content] of expected) {
    const abs = join(repoRoot, MIRROR_DIR, file);
    if (!existsSync(abs)) problems.push(`missing ${file}`);
    else if (readFileSync(abs, 'utf8') !== content) problems.push(`stale ${file}`);
  }
  for (const file of existingFiles(MIRROR_DIR)) {
    if (!expected.has(file)) problems.push(`extra ${file}`);
  }
  return problems;
}

if (process.argv[1]?.endsWith('sync-backup-agent.mjs')) {
  repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
  if (process.argv.includes('--check')) {
    const problems = findDrift();
    if (problems.length) {
      console.error(`Backup mirror is out of date (run node scripts/sync-backup-agent.mjs):\n${problems.join('\n')}`);
      process.exit(1);
    }
    console.log('Backup mirror is in sync.');
  } else {
    rmSync(join(repoRoot, MIRROR_DIR), { recursive: true, force: true });
    for (const [file, content] of buildMirror()) {
      const abs = join(repoRoot, MIRROR_DIR, file);
      mkdirSync(dirname(abs), { recursive: true });
      writeFileSync(abs, content);
    }
    console.log(`Wrote ${MIRROR_DIR}`);
  }
}
